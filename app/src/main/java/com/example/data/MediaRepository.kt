    // Automatically create auto-genre playlists based on tracks in the database
    suspend fun generateAutoPlaylistsByGenres() = withContext(Dispatchers.IO) {
        val tracks = mediaDao.getAllTracksList()
        val genres = tracks.map { it.genre }.distinct().filter { it.isNotBlank() }

        val existingPlaylists = mediaDao.getAllPlaylistsList()
        for (genre in genres) {
            // Check if playlist for this genre already exists
            val exists = existingPlaylists.any { it.isAutoGenerated && it.targetGenre == genre }
            if (!exists) {
                val playlistId = mediaDao.insertPlaylist(
                    Playlist(
                        name = "Genre: $genre",
                        isAutoGenerated = true,
                        targetGenre = genre
                    )
                )
                // Add all tracks of this genre
                tracks.filter { it.genre == genre }.forEach { track ->
                    mediaDao.insertPlaylistTrack(PlaylistTrack(playlistId, track.id))
                }
            }
        }
    }

    // Auto-scan a physical or target folder for files, then group them and insert to room database
    suspend fun scanLocalDirectory(folderPath: String) = withContext(Dispatchers.IO) {
        val folder = File(folderPath)
        if (!folder.exists() || !folder.isDirectory) return@withContext

        val audioExtensions = listOf("mp3", "flac", "wav", "m4a", "ogg")
        val videoExtensions = listOf("mp4", "mkv", "avi", "3gp")

        try {
            folder.walkTopDown().forEach { file ->
                if (file.isFile) {
                    val ext = file.extension.lowercase()
                    val isAudio = ext in audioExtensions
                    val isVideo = ext in videoExtensions

                    if (isAudio || isVideo) {
                        val title = file.nameWithoutExtension.replace("_", " ").replace("-", " ")
                        val formatName = ext.uppercase()
                        
                        // Basic default tag logic
                        val parentFolder = file.parentFile?.name ?: "Penyimpanan Utama"
                        val isLossless = ext == "flac" || ext == "wav"
                        val sampleRate = if (isLossless) "96.0 kHz" else "44.1 kHz"
                        val bitRate = if (isLossless) "24-bit Lossless" else "320 kbps"

                        val mediaTrack = MediaTrack(
                            title = title,
                            artist = "Artis Lokal ($parentFolder)",
                            album = parentFolder,
                            genre = "Lokal",
                            filePath = file.absolutePath,
                            isVideo = isVideo,
                            duration = 180000L, // Mock standard duration or calculate
                            format = formatName,
                            sampleRate = sampleRate,
                            bitRate = bitRate,
                            lyricsLrc = "[00:00.00]Lirik lokal untuk $title\n[00:10.00]Sedang diputar dari folder $parentFolder",
                            isDownloaded = true
                        )
                        mediaDao.insertTrack(mediaTrack)
                    }
                }
            }
        } catch (e: Exception) {
            Log.e("MediaRepository", "Failed folder scan for path: $folderPath", e)
        }
    }

    // SAF DocumentTree scanner to load files directly from users selected folder securely
    suspend fun scanDocumentTree(context: Context, treeUri: Uri) = withContext(Dispatchers.IO) {
        val resolver = context.contentResolver
        val docId = try {
            DocumentsContract.getTreeDocumentId(treeUri)
        } catch (e: Exception) {
            DocumentsContract.getDocumentId(treeUri)
        }
        val childrenUri = DocumentsContract.buildChildDocumentsUriUsingTree(treeUri, docId)

        val projection = arrayOf(
            DocumentsContract.Document.COLUMN_DOCUMENT_ID,
            DocumentsContract.Document.COLUMN_DISPLAY_NAME,
            DocumentsContract.Document.COLUMN_MIME_TYPE
        )

        val audioExtensions = listOf("mp3", "flac", "wav", "m4a", "ogg")
        val videoExtensions = listOf("mp4", "mkv", "avi", "3gp")

        try {
            resolver.query(childrenUri, projection, null, null, null)?.use { cursor ->
                val idCol = cursor.getColumnIndexOrThrow(DocumentsContract.Document.COLUMN_DOCUMENT_ID)
                val nameCol = cursor.getColumnIndexOrThrow(DocumentsContract.Document.COLUMN_DISPLAY_NAME)
                val mimeCol = cursor.getColumnIndexOrThrow(DocumentsContract.Document.COLUMN_MIME_TYPE)

                while (cursor.moveToNext()) {
                    val docIdVal = cursor.getString(idCol)
                    val displayName = cursor.getString(nameCol) ?: "Berkas Tanpa Nama"
                    val mimeType = cursor.getString(mimeCol) ?: ""

                    val ext = displayName.substringAfterLast('.', "").lowercase()
                    val isAudio = mimeType.startsWith("audio/") || ext in audioExtensions
                    val isVideo = mimeType.startsWith("video/") || ext in videoExtensions

                    if (isAudio || isVideo) {
                        val fileUri = DocumentsContract.buildDocumentUriUsingTree(treeUri, docIdVal)
                        val title = displayName.substringBeforeLast('.')
                        val formatName = if (ext.isNotBlank()) ext.uppercase() else if (isVideo) "MP4" else "MP3"

                        val mediaTrack = MediaTrack(
                            title = title,
                            artist = "Artis Lokal (SAF)",
                            album = "Folder Pilihan",
                            genre = "Lokal",
                            filePath = fileUri.toString(),
                            isVideo = isVideo,
                            duration = 180000L,
                            format = formatName,
                            isDownloaded = true,
                            lyricsLrc = "[00:00.00]Lirik lokal untuk $title\n[00:10.00]Sedang diputar dari folder pilihan Anda."
                        )
                        mediaDao.insertTrack(mediaTrack)
                    }
                }
            }
        } catch (e: Exception) {
            Log.e("MediaRepository", "Error scanning children documents of treeUri", e)
        }
    }

    // Auto-scan using Android MediaStore to standardly list and load music & videos from phone storage
    suspend fun scanMediaStore(context: Context) = withContext(Dispatchers.IO) {
        val contentResolver = context.contentResolver
        
        // 1. Query Audio from MediaStore
        try {
            val audioUri = android.provider.MediaStore.Audio.Media.EXTERNAL_CONTENT_URI
            val audioProjection = arrayOf(
                android.provider.MediaStore.Audio.Media._ID,
                android.provider.MediaStore.Audio.Media.TITLE,
                android.provider.MediaStore.Audio.Media.ARTIST,
                android.provider.MediaStore.Audio.Media.ALBUM,
                android.provider.MediaStore.Audio.Media.DATA,
                android.provider.MediaStore.Audio.Media.DURATION
            )
            
            contentResolver.query(audioUri, audioProjection, null, null, null)?.use { cursor ->
                val titleColumn = cursor.getColumnIndexOrThrow(android.provider.MediaStore.Audio.Media.TITLE)
                val artistColumn = cursor.getColumnIndexOrThrow(android.provider.MediaStore.Audio.Media.ARTIST)
                val albumColumn = cursor.getColumnIndexOrThrow(android.provider.MediaStore.Audio.Media.ALBUM)
                val dataColumn = cursor.getColumnIndexOrThrow(android.provider.MediaStore.Audio.Media.DATA)
                val durationColumn = cursor.getColumnIndexOrThrow(android.provider.MediaStore.Audio.Media.DURATION)
                
                while (cursor.moveToNext()) {
                    val titleVal = cursor.getString(titleColumn) ?: "Lagu Tanpa Judul"
                    val artistVal = cursor.getString(artistColumn) ?: "Artis Tidak Dikenal"
                    val albumVal = cursor.getString(albumColumn) ?: "Album Lokal"
                    val dataVal = cursor.getString(dataColumn) ?: ""
                    val durationVal = cursor.getLong(durationColumn)
                    
                    if (dataVal.isNotBlank()) {
                        val file = File(dataVal)
                        // Note: file.exists() might be false under scoped storage, but the MediaStore entry itself is playable/queryable
                        val ext = file.extension.uppercase().ifBlank { "MP3" }
                        val mediaTrack = MediaTrack(
                            title = titleVal,
                            artist = if (artistVal == "<unknown>") "Artis Lokal" else artistVal,
                            album = if (albumVal == "<unknown>") "Pustaka Handphone" else albumVal,
                            genre = "Lokal",
                            filePath = dataVal,
                            isVideo = false,
                            duration = if (durationVal > 0) durationVal else 180000L,
                            format = ext,
                            sampleRate = "44.1 kHz",
                            bitRate = "320 kbps",
                            isDownloaded = true,
                            lyricsLrc = "[00:00.00]Lirik lokal untuk $titleVal\n[00:10.00]Sedang diputar dari file perangkat Anda"
                        )
                        mediaDao.insertTrack(mediaTrack)
                    }
                }
            }
        } catch (e: Exception) {
            Log.e("MediaRepository", "Failed scanning audio from MediaStore", e)
        }

        // 2. Query Video from MediaStore
        try {
            val videoUri = android.provider.MediaStore.Video.Media.EXTERNAL_CONTENT_URI
            val videoProjection = arrayOf(
                android.provider.MediaStore.Video.Media._ID,
                android.provider.MediaStore.Video.Media.TITLE,
                android.provider.MediaStore.Video.Media.DATA,
                android.provider.MediaStore.Video.Media.DURATION
            )
            contentResolver.query(videoUri, videoProjection, null, null, null)?.use { cursor ->
                val titleColumn = cursor.getColumnIndexOrThrow(android.provider.MediaStore.Video.Media.TITLE)
                val dataColumn = cursor.getColumnIndexOrThrow(android.provider.MediaStore.Video.Media.DATA)
                val durationColumn = cursor.getColumnIndexOrThrow(android.provider.MediaStore.Video.Media.DURATION)
                
                while (cursor.moveToNext()) {
                    val titleVal = cursor.getString(titleColumn) ?: "Video Tanpa Judul"
                    val dataVal = cursor.getString(dataColumn) ?: ""
                    val durationVal = cursor.getLong(durationColumn)
                    
                    if (dataVal.isNotBlank()) {
                        val file = File(dataVal)
                        val ext = file.extension.uppercase().ifBlank { "MP4" }
                        val mediaTrack = MediaTrack(
                            title = titleVal,
                            artist = "Video Perangkat",
                            album = "Galeri Handphone",
                            genre = "Lokal Video",
                            filePath = dataVal,
                            isVideo = true,
                            duration = if (durationVal > 0) durationVal else 180000L,
                            format = ext,
                            sampleRate = "48.0 kHz",
                            bitRate = "MPEG-4",
                            isDownloaded = true,
                            lyricsLrc = "[00:00.00]Video Lokal: $titleVal"
                        )
                        mediaDao.insertTrack(mediaTrack)
                    }
                }
            }
        } catch (e: Exception) {
            Log.e("MediaRepository", "Failed scanning video from MediaStore", e)
        }
    }

